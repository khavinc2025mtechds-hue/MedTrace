"""Require reviewed labels and separate duplicate narratives across splits."""
import hashlib
import pandas as pd
from sklearn.model_selection import GroupShuffleSplit

def labeled_split(csv_path,cutoff=None):
    df=pd.read_csv(csv_path).fillna('')
    required={'narrative','label','label_source'}
    if not required.issubset(df):raise ValueError('Need narrative,label,label_source columns. Labels must be reviewed or curated code mappings, not generated by the classifier.')
    if not df.label_source.isin(['human_review','curated_code_mapping']).all():raise ValueError('Unsupported label provenance')
    df=df[df.narrative.str.strip().ne('') & df.label.str.strip().ne('')].copy()
    df['group']=df.narrative.map(lambda t:hashlib.sha256(' '.join(t.casefold().split()).encode()).hexdigest())
    if df.groupby('group').label.nunique().max()>1:raise ValueError('Conflicting labels on duplicate narratives')
    if len(df)<20 or df.label.nunique()<2:raise ValueError('Need at least 20 labeled rows and two classes')
    if cutoff:
        dates=pd.to_datetime(df.date_received,errors='raise');train=df[dates<pd.Timestamp(cutoff)];test=df[dates>=pd.Timestamp(cutoff)];train=train[~train.group.isin(test.group)]
    else:
        tr,te=next(GroupShuffleSplit(n_splits=1,test_size=.2,random_state=42).split(df,groups=df.group));train=df.iloc[tr];test=df.iloc[te]
    if train.empty or test.empty or train.label.nunique()<2:raise ValueError('Split is too small or contains one training class')
    if not set(test.label).issubset(set(train.label)):raise ValueError('Test has labels absent from train; increase labeled dataset')
    return train,test
